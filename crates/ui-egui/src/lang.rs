/// UI language. `code()` is the persisted prefs value; `native_name()` is
/// the picker's label (each language names itself).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Ar,
    Fa,
    Ur,
    Fr,
    It,
    De,
    Es,
    Pt,
    Tr,
    La,
    Ru,
    Zh,
    Ja,
    Ko,
    Hi,
}

pub const ALL: &[Lang] = &[
    Lang::En,
    Lang::Ar,
    Lang::Fa,
    Lang::Ur,
    Lang::Fr,
    Lang::It,
    Lang::De,
    Lang::Es,
    Lang::Pt,
    Lang::Tr,
    Lang::La,
    Lang::Ru,
    Lang::Zh,
    Lang::Ja,
    Lang::Ko,
    Lang::Hi,
];

impl Lang {
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Ar => "ar",
            Lang::Fa => "fa",
            Lang::Ur => "ur",
            Lang::Fr => "fr",
            Lang::It => "it",
            Lang::De => "de",
            Lang::Es => "es",
            Lang::Pt => "pt",
            Lang::Tr => "tr",
            Lang::La => "la",
            Lang::Ru => "ru",
            Lang::Zh => "zh",
            Lang::Ja => "ja",
            Lang::Ko => "ko",
            Lang::Hi => "hi",
        }
    }

    /// Unknown/missing codes and region/script variants fall back to the
    /// primary language (`zh-Hans` → `zh`, `pt-BR` → `pt`), then English.
    pub fn from_code(code: &str) -> Self {
        let base = code.split(['-', '_']).next().unwrap_or(code);
        ALL.iter().copied().find(|l| l.code().eq_ignore_ascii_case(base)).unwrap_or(Lang::En)
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Ar => "العربية",
            Lang::Fa => "فارسی",
            Lang::Ur => "اردو",
            Lang::Fr => "Français",
            Lang::It => "Italiano",
            Lang::De => "Deutsch",
            Lang::Es => "Español",
            Lang::Pt => "Português",
            Lang::Tr => "Türkçe",
            Lang::La => "Latina",
            Lang::Ru => "Русский",
            Lang::Zh => "简体中文",
            Lang::Ja => "日本語",
            Lang::Ko => "한국어",
            Lang::Hi => "हिन्दी",
        }
    }

    /// Whether this language's chrome should mirror right-to-left.
    pub fn rtl(self) -> bool {
        matches!(self, Lang::Ar | Lang::Fa | Lang::Ur)
    }
}

