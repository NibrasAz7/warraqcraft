/// Substitute `{name}` placeholders in a catalog format string, then put
/// the finished text in the display order egui's per-font-run layout needs.
pub fn fmt(fmt: &'static str, pairs: &[(&str, &str)]) -> String {
    let mut out = fmt.to_string();
    for (k, v) in pairs {
        out = out.replace(&format!("{{{k}}}"), v);
    }
    view(&out).into_owned()
}

