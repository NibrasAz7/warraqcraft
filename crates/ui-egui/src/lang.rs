//! UI localization. `Strings` is the complete message catalog — every
//! language is one `Strings` literal and the compiler refuses a partial
//! table, so adding a language is: add the `Lang` variant, copy `EN`,
//! translate each field.
//!
//! Localized entries are stored in **logical order** (normal Unicode text).
//! egui's harfrust shaper handles the letters inside one run, while egui's
//! text layout still places font runs in input order. [`view`] therefore
//! does paragraph-level bidirectional reordering only: same-direction runs
//! reach the painter in screen order and each RTL word remains in logical
//! order for the shaper. Never pre-shape into presentation forms here.

